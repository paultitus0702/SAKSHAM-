import React from 'react';
import type { PipelineResultResponse } from '../api/client';
import type { NavItem } from './Sidebar';

type ModuleTab = Exclude<NavItem, 'upload' | 'benchmarks'>;

interface PipelineModuleViewProps {
  tab: ModuleTab;
  result: PipelineResultResponse | null;
  running: boolean;
  onNavigate: (tab: NavItem) => void;
}

const MODULE_DETAILS: Record<ModuleTab, { title: string; phase: string; description: string }> = {
  overview: {
    title: 'Model Overview',
    phase: 'PHASE 2',
    description: 'Input identity and canonical model dimensions from the latest pipeline result.',
  },
  fingerprint: {
    title: 'Structural Fingerprint',
    phase: 'PHASE 3',
    description: 'Measured sparse structure and conservative fingerprint signals.',
  },
  structures: {
    title: 'Detected Structures',
    phase: 'PHASE 3',
    description: 'Structure tags and candidate classifications returned by the fingerprint stage.',
  },
  health: {
    title: 'Numerical Health',
    phase: 'PHASE 3 / 6',
    description: 'Available coefficient-scale and sparse-matrix diagnostics.',
  },
  isg: {
    title: 'Structure Graph (ISG)',
    phase: 'PHASE 4',
    description: 'Reported variable-constraint and objective graph summary metrics.',
  },
  strategy: {
    title: 'Recommended Strategy',
    phase: 'PHASE 5',
    description: 'Backend recommendation, confidence, rationale, and warnings.',
  },
  progress: {
    title: 'Solve Progress',
    phase: 'PHASE 6',
    description: 'Solver execution status and measured elapsed time, when available.',
  },
  results: {
    title: 'Optimization Results',
    phase: 'PHASE 6',
    description: 'Solver-reported status, objective, and primal values when returned.',
  },
  sakshi: {
    title: 'Sakshi Verification',
    phase: 'PHASE 7',
    description: 'Independent feasibility, bounds, integrality, and objective checks.',
  },
  certificate: {
    title: 'Solve Certificate',
    phase: 'PHASE 8',
    description: 'Certificate status and digest generated by the existing pipeline.',
  },
};

const formatValue = (value: unknown): string => {
  if (value === null || value === undefined || value === '') return 'Unavailable';
  if (typeof value === 'number') {
    return Number.isFinite(value)
      ? new Intl.NumberFormat('en', { maximumSignificantDigits: 8 }).format(value)
      : 'Unavailable';
  }
  if (typeof value === 'boolean' || typeof value === 'string') return String(value);
  if (Array.isArray(value)) {
    if (value.length === 0) return 'None';
    const preview = value.slice(0, 12).map(formatValue).join(', ');
    return value.length > 12 ? `${preview}, ... (${value.length} total)` : preview;
  }
  return JSON.stringify(value);
};

const statusColor = (status: string): string => {
  if (['HEALTHY', 'VERIFIED', 'OPTIMAL', 'COMPLETE', 'GENERATED', 'SATISFIED'].includes(status)) {
    return 'text-emerald-400';
  }
  if (['FAILED', 'INVALID', 'UNHEALTHY', 'INFEASIBLE', 'UNBOUNDED', 'ERROR'].includes(status)) {
    return 'text-red-400';
  }
  return 'text-amber-300';
};

const Metric = ({ label, value }: { label: string; value: unknown }) => (
  <div className="min-w-0 border-l-2 border-industrial-700 pl-3">
    <dt className="text-[10px] font-mono uppercase text-slate-500">{label}</dt>
    <dd className="mt-1 break-words text-sm font-mono text-slate-200">{formatValue(value)}</dd>
  </div>
);

const MetricGrid = ({ items }: { items: Array<[string, unknown]> }) => (
  <dl className="grid grid-cols-1 gap-x-6 gap-y-4 sm:grid-cols-2 xl:grid-cols-4">
    {items.map(([label, value]) => <Metric key={label} label={label} value={value} />)}
  </dl>
);

const TagList = ({ values }: { values: string[] }) => (
  values.length > 0 ? (
    <ul className="flex flex-wrap gap-2">
      {values.map((value) => (
        <li key={value} className="border border-industrial-700 bg-industrial-950 px-2 py-1 font-mono text-[11px] text-slate-300">
          {value}
        </li>
      ))}
    </ul>
  ) : <p className="text-sm text-slate-500">No structure tags were returned.</p>
);

const Warnings = ({ warnings }: { warnings: string[] }) => (
  warnings.length > 0 ? (
    <ul className="space-y-1 text-xs text-amber-200/80">
      {warnings.map((warning, index) => <li key={`${warning}-${index}`}>{warning}</li>)}
    </ul>
  ) : <p className="text-sm text-slate-500">No warnings were returned.</p>
);

const EmptyState = ({ running, onNavigate }: Pick<PipelineModuleViewProps, 'running' | 'onNavigate'>) => (
  <section className="border border-industrial-800 bg-industrial-900 p-6" aria-live="polite">
    <h2 className="text-base font-semibold text-slate-100">
      {running ? 'Model run in progress' : 'Run a model first'}
    </h2>
    <p className="mt-2 max-w-2xl text-sm text-slate-400">
      {running
        ? 'The solve endpoint returns stage details when execution completes. Live progress percentages are not available.'
        : 'This module will display analysis and solve data from the shared pipeline result.'}
    </p>
    {!running && (
      <button
        type="button"
        onClick={() => onNavigate('upload')}
        className="mt-4 inline-flex min-h-10 items-center border border-industrial-700 bg-industrial-800 px-4 text-sm font-semibold text-slate-200 transition hover:bg-industrial-700"
      >
        Open Model Upload
      </button>
    )}
  </section>
);

export const PipelineModuleView: React.FC<PipelineModuleViewProps> = ({
  tab,
  result,
  running,
  onNavigate,
}) => {
  const details = MODULE_DETAILS[tab];
  if (!result) return <EmptyState running={running} onNavigate={onNavigate} />;

  const fingerprint = result.fingerprint;
  const health = result.health;
  const isgSummary = result.isg?.summary ?? {};
  const strategy = result.strategy;
  const solver = result.solver_result;
  const verification = result.verification;
  const certificate = result.certificate;

  let content: React.ReactNode;
  switch (tab) {
    case 'overview':
      content = (
        <MetricGrid items={[
          ['Filename', result.input.name],
          ['Input format', result.input.format?.toUpperCase() ?? null],
          ['Model type', result.model_summary ? `${result.model_summary.sense.toUpperCase()} ${result.model_summary.is_mip ? 'MIP' : 'LP'}` : null],
          ['Variables', result.model_summary?.num_variables],
          ['Constraints', result.model_summary?.num_constraints],
          ['Nonzeros', result.model_summary?.num_nonzeros],
        ]} />
      );
      break;
    case 'fingerprint':
      content = fingerprint ? (
        <div className="space-y-5">
          <p className={`font-mono text-sm font-semibold ${statusColor(fingerprint.status)}`}>
            Fingerprint status: {fingerprint.status}
          </p>
          <MetricGrid items={[
            ['Variables', fingerprint.num_vars],
            ['Constraints', fingerprint.num_constrs],
            ['Nonzeros', fingerprint.num_nonzeros],
            ['Density', fingerprint.density],
            ['Conservation rows', fingerprint.conservation_rows_detected],
            ['Knapsack rows', fingerprint.knapsack_rows_detected],
          ]} />
          <div className="space-y-2">
            <h3 className="text-[10px] font-mono uppercase text-slate-500">Fingerprint tags</h3>
            <TagList values={fingerprint.tags} />
          </div>
          <details className="border-t border-industrial-800 pt-3">
            <summary className="cursor-pointer text-xs font-mono text-slate-400">Raw fingerprint metrics</summary>
            <dl className="mt-3 grid grid-cols-1 gap-3 sm:grid-cols-2">
              {Object.entries(fingerprint.raw_metrics).map(([key, value]) => (
                <Metric key={key} label={key.replaceAll('_', ' ')} value={value} />
              ))}
            </dl>
          </details>
        </div>
      ) : <Unavailable stage="Fingerprint" />;
      break;
    case 'structures': {
      const rawMetrics = fingerprint?.raw_metrics ?? {};
      content = fingerprint ? (
        <div className="space-y-5">
          <TagList values={fingerprint.tags} />
          <MetricGrid items={[
            ['Fingerprint status', fingerprint.status],
            ['Network structure', rawMetrics.network_structure_status],
            ['Block structure', rawMetrics.block_structure_status],
            ['Conservation row candidates', fingerprint.conservation_rows_detected],
            ['Knapsack row candidates', fingerprint.knapsack_rows_detected],
          ]} />
          <p className="text-xs text-slate-500">
            Candidate labels are the backend’s measured classifications; they do not imply decomposition or a confirmed mathematical model class.
          </p>
        </div>
      ) : <Unavailable stage="Structure detection" />;
      break;
    }
    case 'health': {
      const displayStatus = health?.status === 'HEALTHY'
        ? 'HEALTHY'
        : health?.status === 'UNAVAILABLE'
          ? 'UNAVAILABLE'
          : health
            ? 'UNHEALTHY'
            : 'UNAVAILABLE';
      content = health ? (
        <div className="space-y-5">
          <div>
            <p className={`text-lg font-mono font-bold ${statusColor(displayStatus)}`}>{displayStatus}</p>
            <p className="mt-1 text-xs text-slate-500">Backend status: {health.status}</p>
          </div>
          <MetricGrid items={[
            ['Dynamic range', health.dynamic_range],
            ['Estimated condition number', health.estimated_condition_number],
            ['Minimum coefficient magnitude', health.coefficient_min_abs],
            ['Maximum coefficient magnitude', health.coefficient_max_abs],
            ['Nonzero coefficients', health.nonzero_coefficient_count],
            ['Stored coefficients', health.stored_coefficient_count],
            ['Explicit zeros', health.explicit_zero_count],
            ['Zero rows / columns', `${health.zero_row_count} / ${health.zero_column_count}`],
            ['Non-finite coefficients', health.has_non_finite_coefficients],
          ]} />
          <p className="border-t border-industrial-800 pt-3 text-sm text-slate-400">{health.details}</p>
        </div>
      ) : <Unavailable stage="Numerical health" />;
      break;
    }
    case 'isg': {
      const reportedMetrics = Object.entries(isgSummary);
      content = result.isg ? (
        <div className="space-y-5">
          <p className={`font-mono text-sm font-semibold ${statusColor(result.isg.status)}`}>
            ISG status: {result.isg.status}
          </p>
          <MetricGrid items={reportedMetrics.map(([key, value]) => [key.replaceAll('_', ' '), value])} />
          <p className="text-xs text-slate-500">
            The solve response includes ISG summary metrics, not edge records; no graph edges are inferred in this view.
          </p>
        </div>
      ) : <Unavailable stage="ISG" />;
      break;
    }
    case 'strategy':
      content = strategy ? (
        <div className="space-y-5">
          <MetricGrid items={[
            ['Primary strategy', strategy.primary_strategy],
            ['Algorithm', strategy.primary_algorithm],
            ['Recommendation status', strategy.status],
            ['Confidence', strategy.confidence],
          ]} />
          <div className="space-y-2">
            <h3 className="text-[10px] font-mono uppercase text-slate-500">Rationale</h3>
            <Warnings warnings={strategy.rationale} />
          </div>
          <div className="space-y-2 border-t border-industrial-800 pt-4">
            <h3 className="text-[10px] font-mono uppercase text-slate-500">Strategy warnings</h3>
            <Warnings warnings={strategy.warnings} />
          </div>
        </div>
      ) : <Unavailable stage="Strategy recommendation" />;
      break;
    case 'progress':
      content = (
        <MetricGrid items={[
          ['Pipeline stage', result.stage],
          ['Pipeline status', result.status],
          ['Parser status', result.parser_status],
          ['Solver executed', result.solver_executed],
          ['Solver name', solver?.solver_name ?? result.selected_solver],
          ['Solver status', solver?.status],
          ['Solve time (seconds)', solver?.wall_time_seconds],
        ]} />
      );
      break;
    case 'results':
      content = (
        <div className="space-y-5">
          <MetricGrid items={[
            ['Solver', solver?.solver_name ?? result.selected_solver],
            ['Solver status', solver?.status],
            ['Objective value', solver?.objective_value],
            ['Solve time (seconds)', solver?.wall_time_seconds],
            ['Iterations', solver?.iteration_count],
          ]} />
          {solver?.primal_solution ? (
            <details className="border-t border-industrial-800 pt-3">
              <summary className="cursor-pointer text-xs font-mono text-slate-400">
                Primal solution vector ({solver.primal_solution.length} values)
              </summary>
              <pre className="mt-3 max-h-80 overflow-auto whitespace-pre-wrap break-words bg-industrial-950 p-3 font-mono text-xs text-slate-300">
                {solver.primal_solution.map((value, index) => `x[${index}] = ${formatValue(value)}`).join('\n')}
              </pre>
            </details>
          ) : <p className="text-sm text-slate-500">Primal solution is unavailable.</p>}
          {solver?.message && <p className="text-xs text-slate-500">{solver.message}</p>}
        </div>
      );
      break;
    case 'sakshi':
      content = verification ? (
        <div className="space-y-5">
          <p className={`text-lg font-mono font-bold ${statusColor(verification.status)}`}>
            Verification: {verification.status}
          </p>
          <MetricGrid items={[
            ['Solver status', verification.solver_status],
            ['Bounds satisfied', verification.bounds_satisfied],
            ['Constraints satisfied', verification.constraints_satisfied],
            ['Integrality satisfied', verification.integrality_satisfied],
            ['Objective consistent', verification.objective_consistent],
            ['Max constraint violation', verification.max_constraint_violation],
            ['Max bound violation', verification.max_bound_violation],
            ['Max integrality violation', verification.max_integrality_violation],
            ['Objective discrepancy', verification.objective_discrepancy],
          ]} />
          {verification.warnings.length > 0 && (
            <div className="border-t border-industrial-800 pt-4">
              <Warnings warnings={verification.warnings} />
            </div>
          )}
        </div>
      ) : <Unavailable stage="SAKSHI verification" />;
      break;
    case 'certificate':
      content = certificate ? (
        <div className="space-y-5">
          <MetricGrid items={[
            ['Certificate status', certificate.status],
            ['Verification status', certificate.verification_status],
            ['Optimality claim', certificate.optimality_claim],
            ['Solver-reported objective', certificate.solver_reported_objective_value],
            ['Independently calculated objective', certificate.independently_calculated_objective_value],
          ]} />
          <div className="border-t border-industrial-800 pt-4">
            <p className="text-[10px] font-mono uppercase text-slate-500">SHA-256 digest</p>
            <p className="mt-2 break-all font-mono text-xs text-slate-300">{certificate.sha256_hash || 'Unavailable'}</p>
          </div>
        </div>
      ) : <Unavailable stage="Solve certificate" />;
      break;
  }

  return (
    <section className="space-y-5 border border-industrial-800 bg-industrial-900 p-5" aria-live="polite">
      <header className="flex flex-wrap items-start justify-between gap-3 border-b border-industrial-800 pb-4">
        <div>
          <h2 className="text-base font-semibold text-slate-100">{details.title}</h2>
          <p className="mt-1 text-xs text-slate-400">{details.description}</p>
        </div>
        <span className="border border-industrial-800 bg-industrial-950 px-2 py-1 font-mono text-[10px] text-slate-400">
          {details.phase}
        </span>
      </header>

      <div className="flex flex-wrap items-center justify-between gap-2 text-xs">
        <span className="truncate font-mono text-slate-400">
          {result.input.name ?? 'Model result'} / {result.input.format?.toUpperCase() ?? 'UNKNOWN'}
        </span>
        <span className={`font-mono font-semibold ${statusColor(result.status)}`}>
          {result.status} / {result.stage}
        </span>
      </div>

      {content}

      {result.errors.length > 0 && (
        <div className="space-y-2 border-t border-red-900/70 pt-4" role="alert">
          {result.errors.map((error, index) => (
            <p key={`${error.stage}-${index}`} className="text-xs text-red-300">
              <span className="font-mono">{error.stage}{error.code ? ` / ${error.code}` : ''}</span>: {error.message}
            </p>
          ))}
        </div>
      )}
      {result.warnings.length > 0 && (
        <div className="space-y-2 border-t border-amber-900/50 pt-4">
          <h3 className="text-[10px] font-mono uppercase text-amber-300">Pipeline warnings</h3>
          <Warnings warnings={result.warnings} />
        </div>
      )}
    </section>
  );
};

const Unavailable = ({ stage }: { stage: string }) => (
  <p className="text-sm text-slate-500">{stage} data is unavailable in this pipeline result.</p>
);